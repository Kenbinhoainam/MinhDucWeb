import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';

const project = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(import.meta.url);

export const sources = Object.freeze([
  'brand-rights.js',
  'demo-translations.js',
  'v13-copy.js',
  'v14-copy.js',
  'prototype-v17.js',
  'locale-routing.js',
  'flagship-editorial.js',
  'flagship-content.js',
  'contact-media.js',
  'company-profile.js',
  'company-locations.js',
  'app.js',
  'seo-preview.js',
]);

export async function buildRuntime({ minify = true, outputDirectory = path.join(project, 'public') } = {}) {
  const sourceTexts = await Promise.all(sources.map(file => fs.readFile(path.join(project, 'public', file), 'utf8')));
  // A separator prevents adjacent IIFEs from becoming an accidental function call.
  const input = sourceTexts.join('\n;\n');
  // Pages can export the original script scopes with only Node installed.
  // The framework build still uses the compiler already installed with Vite.
  let result = { code: input, warnings: [] };
  if (minify) {
   const viteRequire = createRequire(require.resolve('vite/package.json'));
   const { transform } = viteRequire('esbuild');
   result = await transform(input, {
    loader: 'js',
    sourcefile: 'site-runtime.source.js',
    target: 'es2020',
    minify: true,
    treeShaking: false,
    charset: 'utf8',
    legalComments: 'none',
    sourcemap: false,
    // Keep the original script scopes and window APIs. No imports, tree shaking,
    // property mangling, global defines or application behavior are changed.
   });
  }
  if (result.warnings.length) throw new Error(result.warnings.map(warning => warning.text).join('\n'));
  const digest = createHash('sha256').update(input).digest('hex');
  const output = `/* Generated by scripts/build-runtime.mjs. Source SHA256: ${digest}. Edit the original browser scripts. */\n` + result.code;
  new Script(output, { filename: 'site-runtime.js' });
  await fs.writeFile(path.join(outputDirectory, 'site-runtime.js'), output);
  const inputBytes = sourceTexts.reduce((total, source) => total + Buffer.byteLength(source), 0);
  return {
    sourceCount: sources.length,
    inputBytes,
    outputBytes: Buffer.byteLength(output),
    savedPercent: Number((100 * (1 - Buffer.byteLength(output) / inputBytes)).toFixed(1)),
    gzipBytes: gzipSync(output, { level: 9 }).length,
    originalGzipBytes: sourceTexts.reduce((total, source) => total + gzipSync(source, { level: 9 }).length, 0),
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await buildRuntime()));
}
